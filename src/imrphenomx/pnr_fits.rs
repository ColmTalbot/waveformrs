//! Parameter-space fits of the PNR angles and of the PhenomXCP
//! co-precessing deviations of IMRPhenomXPNR:
//!
//! - the coefficients of the merger-ringdown expressions of `alpha` and
//!   `beta`, `LALSimIMRPhenomX_PNR_coefficients.c` (polynomials of degree
//!   (3, 3, 4) in `eta`, `chi`, `cos(theta)` evaluated by
//!   `IMRPhenomX_PNR_evaluate_coefficient_array`);
//! - the deviations of the (2,2) co-precessing model,
//!   `LALSimIMRPhenomX_PNR_deviations.c` (`XLALSimIMRPhenomXCP_*_l2m2`).
//!
//! Products and sums are fused where the hardware has fused multiply-adds
//! (see [`crate::spintaylor::fp`]).

use crate::spintaylor::fp::{fma, fnms};

/// Coefficients `c[i][j][k]` of `eta^i chi^j cos(theta)^k`.
type Coefficients = [[[f64; 5]; 4]; 4];

/// `IMRPhenomX_PNR_evaluate_coefficient_array`: the sum of
/// `c[i][j][k] eta^i chi^j costheta^k`, accumulated in the order of the C
/// loops with the powers from `pow`.
fn evaluate(coeff: &Coefficients, eta: f64, chi: f64, costheta: f64) -> f64 {
    let mut poly_sum = 0.0;
    for (i, ci) in coeff.iter().enumerate() {
        let eta_i = eta.powf(i as f64);
        for (j, cij) in ci.iter().enumerate() {
            let chi_j = chi.powf(j as f64);
            for (k, &c) in cij.iter().enumerate() {
                poly_sum = fma(c * eta_i * chi_j, costheta.powf(k as f64), poly_sum);
            }
        }
    }
    poly_sum
}

/// `sqrt(1 - costheta^2)`.
#[inline]
fn sin_from_cos(costheta: f64) -> f64 {
    fnms(costheta, costheta, 1.0).sqrt()
}

/// `IMRPhenomX_PNR_alpha_A1_coefficient`.
pub(crate) fn alpha_a1(eta: f64, chi: f64, costheta: f64) -> f64 {
    let a1 = evaluate(&COEFF_A1, eta, chi, costheta);
    chi * sin_from_cos(costheta) * a1 * a1
}

/// `IMRPhenomX_PNR_alpha_A2_coefficient`.
pub(crate) fn alpha_a2(eta: f64, chi: f64, costheta: f64) -> f64 {
    let a2 = evaluate(&COEFF_A2, eta, chi, costheta);
    -chi * sin_from_cos(costheta) * a2 * a2
}

/// `IMRPhenomX_PNR_alpha_A3_coefficient`.
pub(crate) fn alpha_a3(eta: f64, chi: f64, costheta: f64) -> f64 {
    let a3 = evaluate(&COEFF_A3, eta, chi, costheta);
    a3 * a3
}

/// `IMRPhenomX_PNR_alpha_A4_coefficient`.
pub(crate) fn alpha_a4(eta: f64, chi: f64, costheta: f64) -> f64 {
    let a4 = evaluate(&COEFF_A4, eta, chi, costheta);
    a4 * a4
}

/// `IMRPhenomX_PNR_beta_B0_coefficient`.
pub(crate) fn beta_b0(eta: f64, chi: f64, costheta: f64) -> f64 {
    let theta = costheta.acos();
    let b0 = evaluate(&COEFF_B0, eta, chi, costheta);
    chi * theta.sin() * b0
}

/// `IMRPhenomX_PNR_beta_B1_coefficient`.
pub(crate) fn beta_b1(eta: f64, chi: f64, costheta: f64) -> f64 {
    let b1 = evaluate(&COEFF_B1, eta, chi, costheta);
    chi * sin_from_cos(costheta) * b1.exp()
}

/// `IMRPhenomX_PNR_beta_B2_coefficient`.
pub(crate) fn beta_b2(eta: f64, chi: f64, costheta: f64) -> f64 {
    let b2 = evaluate(&COEFF_B2, eta, chi, costheta);
    chi * sin_from_cos(costheta) * (-b2.exp())
}

/// `IMRPhenomX_PNR_beta_B3_coefficient`.
pub(crate) fn beta_b3(eta: f64, chi: f64, costheta: f64) -> f64 {
    evaluate(&COEFF_B3, eta, chi, costheta)
}

/// `IMRPhenomX_PNR_beta_B4_coefficient`.
pub(crate) fn beta_b4(eta: f64, chi: f64, costheta: f64) -> f64 {
    let b4 = evaluate(&COEFF_B4, eta, chi, costheta);
    b4 * b4
}

/// `IMRPhenomX_PNR_beta_B5_coefficient`.
pub(crate) fn beta_b5(eta: f64, chi: f64, costheta: f64) -> f64 {
    let b5 = evaluate(&COEFF_B5, eta, chi, costheta);
    -b5 * b5
}

/// `IMRPhenomX_PNR_beta_Bf_coefficient`.
pub(crate) fn beta_bf(eta: f64, chi: f64, costheta: f64) -> f64 {
    let theta = costheta.acos();
    let bf = evaluate(&COEFF_BF, eta, chi, costheta);
    chi * theta.sin() * bf
}

